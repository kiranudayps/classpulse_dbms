CREATE TRIGGER trg_after_room_update
AFTER UPDATE ON classrooms
FOR EACH ROW
BEGIN
    IF OLD.status != NEW.status THEN
        INSERT INTO room_audit (room_id, old_status, new_status, changed_at)
        VALUES (NEW.id, OLD.status, NEW.status, NOW());
    END IF;
END $$
DELIMITER ;

-- ── 9. STORED PROCEDURES ───────────────────────────────────────
-- SP 1: Available Rooms By Time
DELIMITER $$
CREATE PROCEDURE sp_available_rooms(IN check_day VARCHAR(15), IN check_time TIME)
BEGIN
    SELECT room_number, building, department, capacity
    FROM classrooms
    WHERE id NOT IN (
        SELECT room_id FROM schedules
        WHERE day = check_day 
        AND check_time >= start_time AND check_time < end_time
    );
END $$
DELIMITER ;

-- SP 2: Schedule For Room
DELIMITER $$
CREATE PROCEDURE sp_room_schedule(IN p_room_id INT)
BEGIN
    SELECT day, start_time, end_time, subject, section
    FROM schedules
    WHERE room_id = p_room_id
    ORDER BY FIELD(day, 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday'), start_time;
END $$
DELIMITER ;

-- ── 10. EVENTS ─────────────────────────────────────────────────
-- Replaces Supabase Edge Function to reset rooms
SET GLOBAL event_scheduler = ON;

DELIMITER $$
CREATE EVENT evt_sync_room_status
ON SCHEDULE EVERY 5 MINUTE
DO
BEGIN
    -- Reset occupied rooms past their end time
    UPDATE classrooms
    SET status = 'vacant', current_subject = NULL, current_faculty = NULL, session_start = NULL, session_end = NULL
    WHERE status = 'occupied' AND session_end < CURRENT_TIME();
END $$
DELIMITER ;

