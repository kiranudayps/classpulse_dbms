CREATE PROCEDURE sp_available_rooms(IN check_day VARCHAR(15), IN check_time TIME)
BEGIN
    SELECT room_number, building, department, capacity
    FROM classrooms
    WHERE id NOT IN (
        SELECT room_id FROM schedules
        WHERE day = check_day 
        AND check_time >= start_time AND check_time < end_time
    );
END $$
DELIMITER ;

