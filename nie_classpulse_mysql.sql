CREATE TABLE classrooms (
  id INT AUTO_INCREMENT PRIMARY KEY,
  room_number VARCHAR(10) NOT NULL UNIQUE,
  building VARCHAR(50) NOT NULL,
  floor VARCHAR(20),
  department VARCHAR(20),
  semester VARCHAR(10),
  section VARCHAR(20),
  capacity INT DEFAULT 60,
  facilities VARCHAR(255) DEFAULT 'Projector, Whiteboard, Wi-Fi',
  status ENUM('vacant', 'occupied') NOT NULL DEFAULT 'vacant',
  current_subject VARCHAR(100),
  current_faculty VARCHAR(100),
  session_start TIME,
  session_end TIME,
  updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT chk_capacity CHECK (capacity > 0)
);

CREATE TABLE schedules (
  id INT AUTO_INCREMENT PRIMARY KEY,
  room_id INT,
  room_number VARCHAR(10),
  day ENUM('Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday') NOT NULL,
  start_time TIME NOT NULL,
  end_time TIME NOT NULL,
  subject VARCHAR(100) NOT NULL,
  section VARCHAR(20),
  semester VARCHAR(10),
  FOREIGN KEY (room_id) REFERENCES classrooms(id) ON DELETE CASCADE
);

CREATE TABLE room_audit (
  audit_id INT AUTO_INCREMENT PRIMARY KEY,
  room_id INT,
  old_status ENUM('vacant', 'occupied'),
  new_status ENUM('vacant', 'occupied'),
  changed_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (room_id) REFERENCES classrooms(id) ON DELETE CASCADE
);

